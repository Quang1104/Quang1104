"""Build the profile banner from console-profile.json using only Python."""

import argparse
import json
from dataclasses import dataclass
from html import escape
from itertools import groupby
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "scripts" / "console-profile.json"
PALETTE = {
    "#": "#527ca2",
    "+": "#5dbbf5",
    "=": "#8cd0ea",
    "@": "#eff8ff",
    "%": "#55a696",
    "*": "#8be6b7",
    "o": "#bdebd9",
}


@dataclass(frozen=True)
class Layout:
    width: int
    height: int
    margin: int
    portrait_width: int
    cell: float
    name_size: int
    text_size: int
    name_y: int
    role_y: int
    command_y: int
    output_y: int


LAYOUTS = {
    "profile-console": Layout(1120, 256, 34, 230, 5.35, 48, 22, 108, 144, 192, 224),
    "profile-console-compact": Layout(640, 224, 22, 142, 3.72, 34, 17, 89, 117, 161, 189),
}

MOTION = """  <style>
    @media (prefers-reduced-motion: no-preference) {
      .portrait { animation: draw-portrait .85s steps(14, end) .12s both; }
      .command { animation: type-command .95s steps(15, end) .82s both; }
      .output { animation: reveal .14s ease-out 1.79s both; }
      .cursor { animation: blink .62s step-end 1.94s 3 backwards; }
    }
    @keyframes draw-portrait {
      from { clip-path: inset(0 0 100% 0) fill-box; }
      to { clip-path: inset(0) fill-box; }
    }
    @keyframes reveal { from { opacity: 0; } to { opacity: 1; } }
    @keyframes type-command {
      from { clip-path: inset(0 100% 0 0) fill-box; }
      to { clip-path: inset(0) fill-box; }
    }
    @keyframes blink { 0% { opacity: 0; } 50%, 100% { opacity: 1; } }
  </style>
"""


def render_portrait(rows, layout, panel_top, panel_height):
    """Draw a fixed-width character grid without relying on SVG whitespace."""
    cell = layout.cell
    columns = max(map(len, rows))
    left = layout.margin + (layout.portrait_width - columns * cell) / 2
    top = panel_top + (panel_height - len(rows) * cell) / 2
    lines = []
    for row_number, row in enumerate(rows):
        x = left
        runs = []
        for glyph, group in groupby(row):
            count = len(list(group))
            width = count * cell
            if glyph != " ":
                runs.append(
                    f'<tspan x="{x:.2f}" fill="{PALETTE[glyph]}" textLength="{width:.2f}" '
                    f'lengthAdjust="spacingAndGlyphs">{escape(glyph * count)}</tspan>'
                )
            x += width
        if runs:
            y = top + (row_number + 0.82) * cell
            lines.append(f'      <text y="{y:.2f}">{"".join(runs)}</text>')
    return "\n".join(lines)


def render(profile, layout, animated):
    width, height, margin = layout.width, layout.height, layout.margin
    name, handle, role = (
        escape(profile[field]) for field in ("name", "handle", "role")
    )
    panel_top = 62
    panel_height = height - panel_top - 24
    text_x = margin + layout.portrait_width + 28
    text_end = width - margin
    prompt_x = text_x + round(layout.text_size * 1.05)
    cursor_x = text_x + round(layout.text_size * 8.2)
    portrait = render_portrait(profile["portrait"], layout, panel_top, panel_height)
    style = MOTION if animated else ""

    return f"""<!-- Generated by scripts/render-console.py. -->
<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title description">
  <title id="title">{name} · {role}</title>
  <desc id="description">An ASCII avatar and a Python terminal printing Hello World!</desc>
{style}  <defs>
    <linearGradient id="window" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop stop-color="#0c1728"/>
      <stop offset="1" stop-color="#0e2731"/>
    </linearGradient>
    <pattern id="dots" width="18" height="18" patternUnits="userSpaceOnUse">
      <circle cx="1" cy="1" r="1" fill="#80c5e7" opacity=".13"/>
    </pattern>
  </defs>
  <rect x="1" y="1" width="{width - 2}" height="{height - 2}" rx="20" fill="url(#window)" stroke="#325a6d" stroke-width="2"/>
  <path d="M1 44H{width - 1}" stroke="#325a6d"/>
  <g font-family="Consolas, Menlo, 'Liberation Mono', monospace">
    <circle cx="{margin}" cy="23" r="4.5" fill="#6abdff"/>
    <circle cx="{margin + 16}" cy="23" r="4.5" fill="#75d8bb"/>
    <circle cx="{margin + 32}" cy="23" r="4.5" fill="#e4f3f7" opacity=".85"/>
    <text x="{width / 2:g}" y="29" fill="#a4c4d5" font-size="15" text-anchor="middle">{handle} / profile</text>
    <rect x="{margin}" y="{panel_top}" width="{layout.portrait_width}" height="{panel_height}" rx="13" fill="#101e30" stroke="#2b4a60"/>
    <rect x="{margin}" y="{panel_top}" width="{layout.portrait_width}" height="{panel_height}" rx="13" fill="url(#dots)"/>
    <g class="portrait" font-size="{layout.cell * 1.43:.2f}" font-weight="700" aria-hidden="true">
{portrait}
    </g>
    <text x="{text_x}" y="{layout.name_y}" font-size="{layout.name_size}" fill="#f0f8ff" font-weight="700">{name}</text>
    <text x="{text_x}" y="{layout.role_y}" font-size="{layout.text_size}" fill="#b4d2e1">{role}</text>
    <path d="M{text_x} {layout.command_y - 28}H{text_end}" stroke="#315366"/>
    <g font-size="{layout.text_size}">
      <text x="{text_x}" y="{layout.command_y}" fill="#85e4bb">$</text>
      <text class="command" x="{prompt_x}" y="{layout.command_y}" fill="#f0f8ff"><tspan fill="#8ac8ff">python</tspan> hello.py</text>
      <text class="output" x="{text_x}" y="{layout.output_y}" fill="#85e4bb">Hello World!</text>
      <rect class="cursor" x="{cursor_x}" y="{layout.output_y - layout.text_size + 4}" width="{layout.text_size / 2:g}" height="{layout.text_size}" rx="1.5" fill="#85e4bb"/>
    </g>
  </g>
</svg>
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check the committed SVG files.")
    args = parser.parse_args()
    profile = json.loads(SOURCE.read_text(encoding="utf-8"))
    stale = []

    for name, layout in LAYOUTS.items():
        for animated in (True, False):
            suffix = "" if animated else "-still"
            path = ROOT / "assets" / f"{name}{suffix}.svg"
            svg = render(profile, layout, animated)
            if args.check:
                if not path.exists() or path.read_text(encoding="utf-8") != svg:
                    stale.append(path.name)
            else:
                path.write_bytes(svg.encode("utf-8"))

    if stale:
        parser.exit(1, f"Out of date: {', '.join(stale)}. Run python scripts/render-console.py.\n")
    print("Profile console is up to date." if args.check else "Generated the profile console SVGs.")


if __name__ == "__main__":
    main()
